for (let font of Object.values(AukFonts)) {
	for (let [cyr, lat] of Object.entries(SHARED)) {
		if (!font.glyphs[cyr]) font.glyphs[cyr] = font.glyphs[lat];
	}
	for (let [char, rows] of Object.entries(font.glyphs)) {
		if (rows.length != font.height) throw new Error(`Auk font ${font.id}: glyph ${char} has ${rows.length} rows`);
		let width = rows[0].length;
		if (rows.some(row => row.length != width)) throw new Error(`Auk font ${font.id}: glyph ${char} has uneven rows`);
	}
}

export function fontCharacters(font) {
	return Object.keys(font.glyphs).filter(c => c != ' ');
}

export function glyphFor(font, char) {
	let upper = char.toUpperCase();
	return font.glyphs[upper] || font.glyphs[char] || font.glyphs['?'];
}
